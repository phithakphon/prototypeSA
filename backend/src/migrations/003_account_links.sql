-- Linking a user account to an employee record (HR workflow).
-- 1) One employee record can belong to at most one account, so nobody can be linked to an employee who already
--    has an account (this also protects every existing account's owner).
CREATE UNIQUE INDEX users_employee_id_key ON users (employee_id) WHERE employee_id IS NOT NULL;

-- 2) Audit trail of every link / unlink: who did it, for which account and employee, and when.
CREATE TABLE account_link_audit (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action TEXT NOT NULL CHECK (action IN ('link', 'unlink')),
  user_id INTEGER NOT NULL REFERENCES users (id),
  employee_id INTEGER NOT NULL REFERENCES employees (id),
  performed_by INTEGER NOT NULL REFERENCES users (id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_account_link_audit_user ON account_link_audit (user_id);

-- Same lock-down as the other tables: reachable only through the Express API.
ALTER TABLE account_link_audit ENABLE ROW LEVEL SECURITY;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON account_link_audit FROM anon;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    REVOKE ALL ON account_link_audit FROM authenticated;
  END IF;
END $$;
