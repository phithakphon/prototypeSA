-- PostgreSQL (Supabase) schema. Equivalent to the original SQLite schema (src/legacy-sqlite/001_init.sqlite.sql).
-- Ids are IDENTITY columns (BY DEFAULT) so existing ids can be preserved when importing from SQLite.

CREATE TABLE employees (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_code TEXT NOT NULL UNIQUE,
  first_name TEXT NOT NULL,
  last_name TEXT NOT NULL,
  department TEXT NOT NULL,
  position TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'resigned')),
  start_date DATE NOT NULL,
  resignation_date DATE,
  resignation_reason TEXT,
  -- confidential personal data
  national_id TEXT,
  phone TEXT,
  email TEXT,
  address TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_employees_name ON employees (first_name, last_name);
CREATE INDEX idx_employees_department ON employees (department);
CREATE INDEX idx_employees_status ON employees (status);

CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('employee', 'manager', 'hr', 'finance', 'executive')),
  employee_id INTEGER REFERENCES employees (id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE salaries (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees (id),
  amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
  effective_date DATE NOT NULL,
  note TEXT,
  created_by INTEGER REFERENCES users (id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_salaries_employee ON salaries (employee_id, effective_date);

CREATE TABLE employee_history (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees (id),
  event_type TEXT NOT NULL CHECK (event_type IN ('hired', 'updated', 'position_changed', 'department_changed', 'resigned')),
  description TEXT NOT NULL,
  event_date DATE NOT NULL,
  created_by INTEGER REFERENCES users (id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_history_employee ON employee_history (employee_id);

CREATE TABLE announcements (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  published_at DATE NOT NULL
);

-- Supabase exposes the public schema through its REST API (PostgREST) using the anon/authenticated keys.
-- All access must go through the Express API, so lock these tables for those roles:
-- RLS on with no policies = deny. The backend connects with the database owner role (bypasses RLS).
ALTER TABLE employees ENABLE ROW LEVEL SECURITY;
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE salaries ENABLE ROW LEVEL SECURITY;
ALTER TABLE employee_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE announcements ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON employees, users, salaries, employee_history, announcements FROM anon;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    REVOKE ALL ON employees, users, salaries, employee_history, announcements FROM authenticated;
  END IF;
END $$;
